#include <stdio.h>
#include <stdlib.h>
#include <stdint.h>
#include <string.h>

typedef struct {
    uint8_t key[32];
    uint8_t enckey[32];
    uint8_t deckey[32];
} aes256_context;

void aes256_encrypt_ecb(aes256_context *ctx, uint8_t k[32], uint8_t buf[16]);

int main() {
    aes256_context ctx;
    uint8_t k[32] = {
        0x00,0x01,0x02,0x03,0x04,0x05,0x06,0x07,
        0x08,0x09,0x0a,0x0b,0x0c,0x0d,0x0e,0x0f,
        0x10,0x11,0x12,0x13,0x14,0x15,0x16,0x17,
        0x18,0x19,0x1a,0x1b,0x1c,0x1d,0x1e,0x1f
    };
    uint8_t buf[16] = {
        0x00,0x11,0x22,0x33,0x44,0x55,0x66,0x77,
        0x88,0x99,0xaa,0xbb,0xcc,0xdd,0xee,0xff
    };
    uint8_t original_buf[16];
    int i;

    memcpy(original_buf, buf, 16);

    for (i = 0; i < 1000000; i++) {
        memcpy(buf, original_buf, 16);
        memset(&ctx, 0, sizeof(ctx));
        aes256_encrypt_ecb(&ctx, k, buf);
    }

    printf("buf[0]: 0x%02x\n", buf[0]);
    return 0;
}
